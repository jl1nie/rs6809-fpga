#!/usr/bin/env python3
"""Make m6809/cpu09p_dbg.vhd from John Kent's cpu09p.vhd (multicomp6809,
GPL-3.0-or-later) by adding the ports the ICE needs:

  dbg_regs   out  CC A B DP X Y U S PC (112 bits), always visible
  dbg_halted out  the CPU is in its halt state (registers are settled)
  dbg_pcn    out  the PC the next instruction starts at, valid when
                  lic_out is high (the last cycle of an instruction)
  dbg_brk    in   halt at this instruction boundary, like the halt input
                  (a breakpoint on dbg_pcn)
  dbg_we, dbg_sel, dbg_wd  in  write a register (sel 0 CC, 1 A, 2 B, 3 DP,
                  4 X, 5 Y, 6 U, 7 S, 8 PC) while halted

usage: patch-cpu09p.py cpu09p.vhd m6809/cpu09p_dbg.vhd
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
t = open(src, encoding="latin-1").read()

t = t.replace("entity cpu09p is", "entity cpu09p_dbg is", 1)
t = t.replace("end cpu09p;", "end cpu09p_dbg;", 1)
t = t.replace("architecture rtl of cpu09p is", "architecture rtl of cpu09p_dbg is", 1)
t = t.replace(
    "      hold     :  in std_logic                      -- hold input (active high) extend bus cycle",
    "      hold     :  in std_logic;                     -- hold input (active high) extend bus cycle\n"
    "      -- rs6809-fpga debug ports\n"
    "      dbg_regs   : out std_logic_vector(111 downto 0); -- cc a b dp x y u s pc\n"
    "      dbg_halted : out std_logic;\n"
    "      dbg_pcn    : out std_logic_vector(15 downto 0);\n"
    "      dbg_brk    : in  std_logic;\n"
    "      dbg_we     : in  std_logic;\n"
    "      dbg_sel    : in  std_logic_vector(3 downto 0);\n"
    "      dbg_wd     : in  std_logic_vector(15 downto 0)",
    1,
)

# register processes: (process label, ctrl signal, select, assignment)
regs = [
    ("pc_reg", "pc_ctrl", "1000", "pc <= dbg_wd;"),
    ("acca_reg", "acca_ctrl", "0001", "acca <= dbg_wd(7 downto 0);"),
    ("accb_reg", "accb_ctrl", "0010", "accb <= dbg_wd(7 downto 0);"),
    ("ix_reg", "ix_ctrl", "0100", "xreg <= dbg_wd;"),
    ("iy_reg", "iy_ctrl", "0101", "yreg <= dbg_wd;"),
    ("sp_reg", "sp_ctrl", "0111", "sp <= dbg_wd;"),
    ("up_reg", "up_ctrl", "0110", "up <= dbg_wd;"),
    ("cc_reg", "cc_ctrl", "0000", "cc <= dbg_wd(7 downto 0);"),
    ("dp_reg", "dp_ctrl", "0011", "dp <= dbg_wd(7 downto 0);"),
]
for label, ctrl, sel, assign in regs:
    m = re.search(rf"^{label}\s*:\s*process", t, re.M)
    assert m, label
    i = t.index(f"case {ctrl} is", m.end())
    j = t.index("end case;", i) + len("end case;")
    body = t[i:j]
    new = (
        f"if dbg_we = '1' and dbg_sel = \"{sel}\" then\n      {assign}\n    else\n    "
        + body
        + "\n    end if;"
    )
    t = t[:i] + new + t[j:]

# breakpoint: enter the halt state at an instruction boundary
old = "        if halt = '1' then\n          state <= halt_state;"
assert old in t
t = t.replace(old, "        if halt = '1' or dbg_brk = '1' then\n          state <= halt_state;", 1)

# outputs: registers, halt state, next PC (the value pc_reg loads now)
arch_begin = t.index("begin", t.index("architecture rtl of cpu09p_dbg is"))
outputs = """begin

----------------------------------
--
-- rs6809-fpga: debug outputs
--
----------------------------------
dbg_regs   <= cc & acca & accb & dp & xreg & yreg & up & sp & pc;
dbg_halted <= '1' when state = halt_state else '0';

dbg_pcn_proc: process( pc_ctrl, pc, out_alu, data_in )
begin
  case pc_ctrl is
  when reset_pc   => dbg_pcn <= (others => '0');
  when load_pc    => dbg_pcn <= out_alu(15 downto 0);
  when pull_lo_pc => dbg_pcn <= pc(15 downto 8) & data_in;
  when pull_hi_pc => dbg_pcn <= data_in & pc(7 downto 0);
  when incr_pc    => dbg_pcn <= pc + 1;
  when others     => dbg_pcn <= pc;
  end case;
end process;
"""
t = t[:arch_begin] + outputs + t[arch_begin + len("begin"):]

header = (
    "-- cpu09p_dbg.vhd: generated by rs6809-fpga tools/patch-cpu09p.py from\n"
    "-- multicomp6809's cpu09p.vhd (John E. Kent, GPL-3.0-or-later); the only\n"
    "-- changes are the dbg_* ports for rs6809's ICE.\n"
)
open(dst, "w", encoding="latin-1").write(header + t)
